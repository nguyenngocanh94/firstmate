#!/usr/bin/env bash
# fm-token-budget-arm.sh <id> - generate and register the token-budget watcher check.
#
# Arms the early-warning check for one task id under this home's state/:
#   1. validates config/token-budget (see fm-token-usage.sh --help for the
#      format), refusing a malformed config so a broken budget cannot silently
#      arm a broken warning,
#   2. writes state/<id>.check.sh - a mode-0700 wrapper that execs
#      bin/fm-token-usage.sh --check against this home's roots,
#   3. registers it through bin/fm-check-register.sh, the existing watcher
#      trust mechanism (hash-bound snapshot; the watcher runs only registered
#      checks).
#
# The check itself re-reads config/token-budget on every poll, so changing the
# budget later needs no re-arm; re-running this script regenerates and
# re-registers the wrapper. An absent config is allowed: the check then stays
# silent (monitoring only), per the reader contract.
#
# Usage:
#   fm-token-budget-arm.sh <id>
#
# Requires jq (via the reader). Read-only except for state/<id>.check.sh and the
# trust file written by fm-check-register.sh.
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
FM_STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"

if [ "$#" -ne 1 ] || ! fm_pr_task_id_valid "$1"; then
  echo "error: usage: fm-token-budget-arm.sh <id>" >&2
  exit 2
fi
ID=$1

[ -d "$FM_STATE" ] && [ ! -L "$FM_STATE" ] || { echo "error: state directory is unavailable" >&2; exit 1; }

CONFIG_OUT=$("$SCRIPT_DIR/fm-token-usage.sh" --check-config 2>&1) || {
  echo "error: $CONFIG_OUT" >&2
  exit 1
}

CHECK="$FM_STATE/$ID.check.sh"
umask 077
TMP=$(mktemp "$FM_STATE/.fm-token-check.XXXXXX") || exit 1
trap '[ -z "${TMP:-}" ] || rm -f -- "$TMP"' EXIT HUP INT TERM
cat > "$TMP" <<EOF
#!/usr/bin/env bash
# Registered token-budget early-warning check for $ID.
# Generated by bin/fm-token-budget-arm.sh; re-run that script to regenerate.
exec "$FM_ROOT/bin/fm-token-usage.sh" --check
EOF
chmod 700 "$TMP" || exit 1
mv -f -- "$TMP" "$CHECK" || exit 1
TMP=

"$SCRIPT_DIR/fm-check-register.sh" "$ID" || { echo "error: check registration failed" >&2; exit 1; }

echo "armed: $CHECK ($CONFIG_OUT)"
